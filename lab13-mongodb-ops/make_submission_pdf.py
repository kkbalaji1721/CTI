"""Generate the submission PDF containing the Docker Hub URLs.
   python make_submission_pdf.py --user <dockerhub-user> --name "Your Name" --roll "ID"
"""
import argparse
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Preformatted

ap = argparse.ArgumentParser()
ap.add_argument("--user", required=True); ap.add_argument("--name", default="")
ap.add_argument("--roll", default=""); ap.add_argument("--out", default="Lab13_Submission.pdf")
a = ap.parse_args()
mongo = f"https://hub.docker.com/r/{a.user}/lab13-mongo"
tools = f"https://hub.docker.com/r/{a.user}/lab13-tools"

S = getSampleStyleSheet()
code = ParagraphStyle("c", parent=S["Code"], fontSize=8, leading=10, backColor=colors.whitesmoke, borderPadding=4)
link = lambda u: f'<link href="{u}" color="blue"><u>{u}</u></link>'
P = lambda t, s="Normal": Paragraph(t, S[s])
doc = SimpleDocTemplate(a.out, pagesize=A4, leftMargin=48, rightMargin=48, topMargin=48, bottomMargin=48)
st = [P("Lab 13 - Deploying MongoDB Replica Sets", "Title")]
if a.name or a.roll: st += [P(f"<b>Student:</b> {a.name} &nbsp;&nbsp; <b>ID:</b> {a.roll}")]
st += [Spacer(1, 10), P("Docker Hub URLs", "Heading2"),
       P(f"<b>MongoDB node image:</b> {link(mongo)}"), Spacer(1, 4),
       P(f"<b>Lab tools / demo image:</b> {link(tools)}"), Spacer(1, 4),
       P(f"<b>Pull commands:</b>"),
       Preformatted(f"docker pull {a.user}/lab13-mongo:1.0\ndocker pull {a.user}/lab13-tools:1.0", code),
       Spacer(1, 10), P("Completed tasks", "Heading2")]
rows = [["Task", "Implementation"],
 ["13.1-1 Compose file, 3 nodes, keyFile auth", "docker-compose.yml: 3 services, --replSet rs0 --auth --keyFile; keyfile generated by keyfile-gen (openssl-equivalent, 756 bytes base64)"],
 ["13.1-2 Keyfile + start", "docker compose up -d (keyfile-gen runs first; wrapper entrypoint sets owner mongodb, mode 400)"],
 ["13.1-3 Initiate + verify", "rs-init service runs rs.initiate() with 3 members; tools/verify_rs.py reports 1 PRIMARY + 2 SECONDARY"],
 ["13.1-4 PyMongo failover", "tools/failover_test.py writes/reads continuously while rs.stepDown() is issued; writes resume on the new primary"],
 ["13.1 Activity: Prometheus exporter", "percona/mongodb_exporter sidecar sharing node 1's network (port 9216) + Prometheus (port 9090)"],
 ["13.2 Kubernetes StatefulSet", "k8s/: headless Service, StatefulSet (3 replicas, PVCs, keyfile InitContainer from Secret), readiness probe on 27017"],
 ["Terraform (Atlas free tier)", "terraform/main.tf: M0 cluster, DB user, IP access list, outputs"]]
rows = [[Paragraph(c, S["Normal"]) for c in r] for r in rows]
t = Table(rows, colWidths=[150, 340], repeatRows=1)
t.setStyle(TableStyle([("BACKGROUND", (0,0), (-1,0), colors.lightgrey), ("GRID", (0,0), (-1,-1), .5, colors.grey), ("VALIGN", (0,0), (-1,-1), "TOP")]))
st += [t, Spacer(1, 10), P("Demonstration", "Heading2"),
       Preformatted(f"export DOCKERHUB_USER={a.user}\ndocker compose pull && docker compose up -d\n"
                    "docker compose run --rm tools python tools/verify_rs.py\n"
                    "docker compose run --rm tools python tools/failover_test.py --stepdown-after 8", code)]
doc.build(st); print("wrote", a.out)
